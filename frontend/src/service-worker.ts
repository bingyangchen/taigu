/// <reference lib="webworker" />
/* eslint-disable no-restricted-globals */

// Workbox Docs: https://developers.google.com/web/tools/workbox/modules

import { clientsClaim } from "workbox-core";
import { ExpirationPlugin } from "workbox-expiration";
import {
  cleanupOutdatedCaches,
  createHandlerBoundToURL,
  precacheAndRoute,
} from "workbox-precaching";
import { registerRoute } from "workbox-routing";
import { NetworkFirst, StaleWhileRevalidate } from "workbox-strategies";

declare const self: ServiceWorkerGlobalScope;

const VERSION = "2026.05.14.01";
console.log(`Service worker version: ${VERSION}`);

clientsClaim();

// Precache all of the assets generated by your build process.
// Their URLs are injected into the manifest variable below.
// This variable must be present somewhere in your service worker file,
// even if you decide not to use precaching. See https://cra.link/PWA
cleanupOutdatedCaches();
precacheAndRoute(self.__WB_MANIFEST);

// Set up App Shell-style routing, so that all navigation requests
// are fulfilled with your index.html shell. Learn more at
// https://developers.google.com/web/fundamentals/architecture/app-shell
const fileExtensionRegexp = new RegExp("/[^/?]+\\.[^/]+$");
registerRoute(
  // Return false to exempt requests from being fulfilled by index.html.
  ({ request, url }) => {
    const isNavigate = request.mode === "navigate";
    const isApiRoute = url.pathname.startsWith("/_");
    const isAsset = fileExtensionRegexp.test(url.pathname);
    return isNavigate && !isApiRoute && !isAsset;
  },
  createHandlerBoundToURL(process.env.PUBLIC_URL + "/index.html"),
);

registerRoute(
  ({ url }) =>
    url.origin === self.location.origin &&
    (url.pathname.endsWith(".png") ||
      url.pathname.endsWith(".jpg") ||
      url.pathname.endsWith(".svg") ||
      url.pathname.endsWith(".webp") ||
      url.pathname.endsWith(".mp4")),
  new StaleWhileRevalidate({
    cacheName: "images",
    plugins: [
      // Ensure that once this runtime cache reaches a maximum size the LRU images are removed.
      new ExpirationPlugin({ maxEntries: 50 }),
    ],
  }),
);

const API_CACHE_NAME = "api-cache";
const getApiPath = (url: URL): string => url.pathname.replace(/^\/api\/?/, "");
const apiCachePaths = new Set([
  "cash-dividends",
  "market/market-index",
  "market/market-index-historical-prices",
  "market/historical-prices",
  "trade-plans",
  "stock-memo/company-info",
  "favorites",
  "handling-fee/discount",
]);
registerRoute(
  ({ request, url }) => request.method === "GET" && apiCachePaths.has(getApiPath(url)),
  new NetworkFirst({
    cacheName: API_CACHE_NAME,
    networkTimeoutSeconds: 3,
    plugins: [
      {
        cacheWillUpdate: async ({ response }) => {
          return response.status < 400 ? response : null;
        },
      },
    ],
  }),
);

registerRoute(
  ({ request, url }) =>
    (request.method === "POST" && getApiPath(url) === "account/logout") ||
    (request.method === "DELETE" && getApiPath(url) === "account/delete"),
  async ({ request }) => {
    await caches.delete(API_CACHE_NAME);
    return fetch(request);
  },
);

self.addEventListener("install", () => {
  self.skipWaiting();
});
