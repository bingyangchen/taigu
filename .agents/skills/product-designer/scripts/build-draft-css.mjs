// Compiles the frontend's design tokens, base styles, and the styles of the
// shared components that drafts use into design/shared/components.css, so a
// draft in design/ renders with the app's real styles instead of copies.
//
// Runs inside the frontend dev image, which has `sass` installed; see the
// product-designer skill for the command. Expects frontend/src at /app/src and
// design/ at /design.

import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire("/app/package.json");
const sass = require("sass");

const SRC_DIR = "/app/src";
const OUT_FILE = "/design/shared/components.css";

// The components a draft may render. A component's `<Name>.scss` holds global
// classes and keeps its class names; its `<Name>.module.scss` is a CSS module,
// whose classes become `<Name>_<class>`, the frontend's dev class name without
// the hash. Add a component here when a draft needs it, along with every
// shared component it renders.
const COMPONENTS = [
  "Button",
  "RoundButton",
  "LabeledInput",
  "SegmentedControl",
  "StockPicker",
  "Modal",
  "FormPageShell",
  "DestructiveActionSection",
];

const TOKENS_SCSS = `
@use "sass:meta";
@use "design_system" as ds;
:root {
  @each $name, $value in meta.module-variables(ds) {
    --#{$name}: #{meta.inspect($value)};
  }
}
`;

// index.scss keeps the page from scrolling because the app scrolls inside its
// own layout; a draft is a plain document, so it lets the page scroll again.
const DRAFT_PAGE_OVERRIDE = `
body {
  height: auto;
  overflow: auto;
}
`;

function compileFile(file) {
  return sass.compile(file, { style: "expanded", loadPaths: [SRC_DIR] }).css;
}

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

// Renames the classes and keyframes of a CSS module the way css-loader scopes
// them, minus the hash. Only rule preludes are rewritten, so values such as
// `0.8rem` or `url("x.svg")` stay untouched.
function scopeModule(css, prefix) {
  const keyframes = [...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]);
  const renameKeyframes = (text) =>
    keyframes.reduce(
      (acc, name) => acc.replace(new RegExp(`\\b${name}\\b`, "g"), `${prefix}_${name}`),
      text,
    );

  let out = "";
  let buffer = "";
  for (const char of css) {
    if (char === "{") {
      const prelude = buffer.trim();
      if (prelude.startsWith("@keyframes")) {
        out += renameKeyframes(buffer);
      } else if (prelude.startsWith("@")) {
        out += buffer;
      } else {
        out += buffer.replace(/\.(-?[_a-zA-Z][\w-]*)/g, `.${prefix}_$1`);
      }
      out += char;
      buffer = "";
    } else if (char === ";" || char === "}") {
      out += /^\s*animation(-name)?\s*:/.test(buffer)
        ? renameKeyframes(buffer)
        : buffer;
      out += char;
      buffer = "";
    } else {
      buffer += char;
    }
  }
  return out + buffer;
}

// Inlines the frontend's SVG assets, whose relative URLs would not resolve
// from design/shared/.
function inlineAssets(css) {
  return css.replace(
    /url\((["']?)(?:\.\.\/)+assets\/([^"')]+)\1\)/g,
    (_, _quote, name) => {
      if (!name.endsWith(".svg")) {
        throw new Error(`Unsupported asset type: ${name}`);
      }
      const data = readFileSync(path.join(SRC_DIR, "assets", name)).toString("base64");
      return `url("data:image/svg+xml;base64,${data}")`;
    },
  );
}

const sections = [
  [
    "Tokens from frontend/src/_design_system.scss",
    sass.compileString(TOKENS_SCSS, { style: "expanded", loadPaths: [SRC_DIR] }).css,
  ],
  [
    "Base styles from frontend/src/index.scss",
    compileFile(path.join(SRC_DIR, "index.scss")),
  ],
  ["Draft-only page override", DRAFT_PAGE_OVERRIDE.trim()],
];

for (const name of COMPONENTS) {
  const dir = path.join(SRC_DIR, "components", name);
  const globalFile = path.join(dir, `${name}.scss`);
  const moduleFile = path.join(dir, `${name}.module.scss`);
  if (!existsSync(globalFile) && !existsSync(moduleFile)) {
    throw new Error(`No styles found for component ${name}`);
  }
  if (existsSync(globalFile)) {
    sections.push([`${name}/${name}.scss`, compileFile(globalFile)]);
  }
  if (existsSync(moduleFile)) {
    sections.push([
      `${name}/${name}.module.scss (classes prefixed with ${name}_)`,
      scopeModule(stripComments(compileFile(moduleFile)), name),
    ]);
  }
}

const header = `/*
 * Generated by .agents/skills/product-designer/scripts/build-draft-css.mjs
 * from frontend/src. Do not edit; regenerate it as the product-designer skill
 * describes.
 */`;
const body = sections
  .map(([title, css]) => `/* ${title} */\n${inlineAssets(css).trim()}`)
  .join("\n\n");

mkdirSync(path.dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, `${header}\n\n${body}\n`);
console.log(`Wrote ${OUT_FILE}`);
